import 'dart:convert';
import 'dart:io';

import 'translate_content_localization_ru.dart' as ru;

const _root = 'assets/languages/spanish';
const _bundlePath = '$_root/localization/support_localizations.json';

void main(List<String> args) {
  final overwrite = args.contains('--overwrite');
  final bundleFile = File(_bundlePath);
  final bundle = Map<String, Object?>.from(jsonDecode(bundleFile.readAsStringSync()) as Map);
  final fields = <_Field>[];
  final course = _read('$_root/curriculum/course.json');
  _collectCourse(fields, course);
  for (final group in const ['vocabulary', 'grammar', 'dialogues', 'readings', 'templates']) {
    final directory = Directory('$_root/$group');
    final files = directory.listSync().whereType<File>().where((f) => f.path.endsWith('.json')).toList()
      ..sort((a, b) => a.path.compareTo(b.path));
    for (final file in files) {
      _collectContent(fields, group, jsonDecode(file.readAsStringSync()));
    }
  }

  final old = <String, Map<String, Object?>>{};
  for (final raw in (bundle['entries'] as List? ?? const [])) {
    final entry = Map<String, Object?>.from(raw as Map);
    old['${entry['type']}|${entry['id']}'] = entry;
  }
  final entries = <String, Map<String, Object?>>{
    for (final entry in old.entries)
      entry.key: {
        'type': entry.value['type'],
        'id': entry.value['id'],
        'fields': Map<String, Object?>.from(entry.value['fields'] as Map),
      },
  };
  var created = 0;
  var skipped = 0;
  var overwritten = 0;
  for (final field in fields) {
    final key = '${field.type}|${field.id}';
    final entry = entries.putIfAbsent(key, () => {
      'type': field.type,
      'id': field.id,
      'fields': <String, Object?>{},
    });
    final values = Map<String, Object?>.from(entry['fields'] as Map);
    final source = field.source.trim();
    final current = values[field.name];
    final currentValues = current is Map
        ? Map<String, Object?>.from(current)
        : <String, Object?>{};
    if (currentValues['ru'] is String &&
        (currentValues['ru'] as String).trim().isNotEmpty &&
        !overwrite) {
      skipped++;
      continue;
    }
    currentValues['uk'] ??= source;
    currentValues['ru'] = _translate(source, field);
    values[field.name] = currentValues;
    if (current is Map && currentValues['ru'] != current['ru']) {
      overwritten++;
    } else {
      created++;
    }
    entry['fields'] = values;
  }

  bundle['schemaVersion'] = 2;
  bundle['sourceSupportLocale'] = 'uk';
  bundle['supportLocales'] = ['uk', 'ru'];
  bundle['entries'] = entries.values.toList()
    ..sort((a, b) {
      final type = '${a['type']}'.compareTo('${b['type']}');
      return type == 0 ? '${a['id']}'.compareTo('${b['id']}') : type;
    });
  bundleFile.writeAsStringSync('${const JsonEncoder.withIndent('  ').convert(bundle)}\n');
  stdout.writeln('Created: $created; skipped existing RU: $skipped; overwritten: $overwritten.');
  if (!overwrite) stdout.writeln('Safe mode: existing RU values were not overwritten.');
}

Map<String, Object?> _read(String path) => Map<String, Object?>.from(jsonDecode(File(path).readAsStringSync()) as Map);

void _collectCourse(List<_Field> out, Map<String, Object?> course) {
  _add(out, 'course', course['id'], 'title', course['title']);
  for (final module in (course['modules'] as List)) {
    final m = Map<String, Object?>.from(module as Map);
    _add(out, 'module', m['id'], 'title', m['title']);
  }
  for (final raw in (course['lessons'] as List)) {
    final lesson = Map<String, Object?>.from(raw as Map);
    final metadata = Map<String, Object?>.from(lesson['metadata'] as Map);
    final id = metadata['id'];
    _add(out, 'lesson', id, 'title', metadata['title']);
    _add(out, 'lesson', id, 'description', metadata['description']);
    _add(out, 'lesson', id, 'communicativeOutcome', lesson['communicativeOutcome']);
    for (final rawObjective in (lesson['objectives'] as List)) {
      final objective = Map<String, Object?>.from(rawObjective as Map);
      _add(out, 'lesson_objective', '$id.${objective['id']}', 'description', objective['description']);
    }
    for (final rawSection in (lesson['sections'] as List)) {
      final section = Map<String, Object?>.from(rawSection as Map);
      _add(out, 'lesson_section', section['id'], 'title', section['title']);
      for (final rawActivity in (section['activities'] as List)) {
        final activity = Map<String, Object?>.from(rawActivity as Map);
        _add(out, 'lesson_activity', activity['id'], 'title', activity['title']);
        final spoken = activity['spokenPractice'];
        if (spoken is Map) {
          _add(out, 'lesson_activity', activity['id'], 'spokenPractice.prompt', spoken['prompt']);
          _add(out, 'lesson_activity', activity['id'], 'spokenPractice.focusCue', spoken['focusCue']);
        }
      }
    }
    final summary = lesson['summary'];
    if (summary is Map) _add(out, 'lesson_summary', summary['id'], 'reviewPrompt', summary['reviewPrompt']);
  }
}

void _collectContent(List<_Field> out, String group, Object? json) {
  for (final raw in (json as List)) {
    final item = Map<String, Object?>.from(raw as Map);
    final type = switch (group) {
      'vocabulary' => 'vocabulary',
      'grammar' => 'grammar',
      'dialogues' => 'dialogue',
      'readings' => 'reading',
      _ => 'exercise_template',
    };
    final id = item['id'];
    if (group == 'vocabulary') {
      _add(out, type, id, 'native_translation', item['native_translation']);
      _add(out, type, id, 'notes', item['notes']);
    } else if (group == 'grammar') {
      _add(out, type, id, 'title', item['title']);
      _add(out, type, id, 'explanation', item['explanation']);
      final examples = item['examples'];
      if (examples is List) for (var i = 0; i < examples.length; i++) _add(out, type, id, 'examples.$i', examples[i]);
    } else if (group == 'dialogues') {
      _add(out, type, id, 'title', item['title']);
      final lines = item['lines'];
      if (lines is List) for (var i = 0; i < lines.length; i++) _add(out, type, id, 'lines.$i.native_translation', (lines[i] as Map)['native_translation']);
    } else if (group == 'readings') {
      _add(out, type, id, 'title', item['title']);
      _add(out, type, id, 'native_translation', item['native_translation']);
    } else {
      _add(out, type, id, 'prompt_template', item['prompt_template']);
      final prompt = item['prompt_template'];
      final options = item['answer_options'];
      if (prompt is String && options is List) for (final rawOption in options) {
        final option = Map<String, Object?>.from(rawOption as Map);
        final label = option['label'];
        if (label is String && _supportOption(prompt, label)) _add(out, type, id, 'answer_options.${option['id']}.label', label);
      }
    }
  }
}

void _add(List<_Field> out, String type, Object? id, String name, Object? source) {
  if (id is String && source is String && source.trim().isNotEmpty) out.add(_Field(type, id, name, source));
}

bool _supportOption(String prompt, String label) {
  if (label.trim().isEmpty || RegExp(r'[¿¡áéíóúñü]').hasMatch(label.toLowerCase())) return false;
  final p = prompt.toLowerCase();
  return p.contains('meaning') || p.contains('translation') || p.contains('what ') || p.contains('where ') || p.contains('which ') || RegExp(r'[А-Яа-яІіЇїЄєҐґ]').hasMatch(label);
}

String _translate(String source, _Field field) {
  if (RegExp(r'[іїєґІЇЄҐ]').hasMatch(source)) return _ukrainianToRussian(source);
  if (RegExp(r'[А-Яа-яЁё]').hasMatch(source) && !RegExp(r'[іїєґІЇЄҐ]').hasMatch(source)) return source;
  return ru.translateRussian(source, type: field.type, id: field.id, fieldName: field.name);
}

